  Postgres + PostGIS               127.0.0.1:${PG_PORT}
  Redis                            127.0.0.1:${REDIS_PORT}

${LAN_HOST} is set once, as LAN_HOST in the root .env. It feeds the
API's CORS and Sanctum allow-lists and the URL baked into the APK.
If it changes: edit .env, run docker compose up -d, rebuild the
APK, and re-run this script.

The panel needs no rebuild when the address changes. It derives
the API origin from whatever host the browser loaded it from.

Host ports are all below 49152 on purpose. Windows reserves
several ranges between 50000 and 60000 for Hyper-V/WSL2, which is
what previously stopped the api container from starting. List them
with:
  netsh.exe interface ipv4 show excludedportrange protocol=tcp

