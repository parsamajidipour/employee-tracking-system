  Admin panel                      http://localhost:${PANEL_PORT}
  API                              http://localhost:${API_PORT}
  API health check                 http://localhost:${API_PORT}/up
  WebSocket (Laravel Reverb)       ws://localhost:${REVERB_PORT}

From another device on the same Wi-Fi
  Admin panel                      http://${LAN_HOST}:${PANEL_PORT}
  API                              http://${LAN_HOST}:${API_PORT}

From the Android emulator
  API                              http://10.0.2.2:${API_PORT}

