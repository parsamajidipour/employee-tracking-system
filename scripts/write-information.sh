#!/usr/bin/env bash
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"

read_env() {
    local file="$1" key="$2" fallback="${3:-}"
    local value
    value="$(grep -E "^${key}=" "$file" 2>/dev/null | tail -1 | cut -d= -f2- | sed 's/^"//; s/"$//')" || true
    echo "${value:-$fallback}"
}

ROOT_ENV="$REPO/.env"
API_ENV="$REPO/api/.env"

LAN_HOST="$(read_env "$ROOT_ENV" LAN_HOST localhost)"
API_PORT="$(read_env "$ROOT_ENV" API_PORT 8000)"
REVERB_PORT="$(read_env "$ROOT_ENV" REVERB_PORT 8080)"
PANEL_PORT="$(read_env "$ROOT_ENV" PANEL_PORT 3000)"
PG_PORT="$(read_env "$ROOT_ENV" POSTGRES_PORT 5432)"
REDIS_PORT="$(read_env "$ROOT_ENV" REDIS_PORT 6379)"
PG_DB="$(read_env "$ROOT_ENV" POSTGRES_DB api)"
PG_USER="$(read_env "$ROOT_ENV" POSTGRES_USER api)"
PG_PASS="$(read_env "$ROOT_ENV" POSTGRES_PASSWORD secret)"

ADMIN_EMAIL="$(read_env "$API_ENV" SEED_ADMIN_EMAIL test@example.com)"
ADMIN_PASS="$(read_env "$API_ENV" SEED_ADMIN_PASSWORD password)"
APP_DEBUG="$(read_env "$API_ENV" APP_DEBUG false)"

STAFF_PASS="$(grep -oE "DEFAULT_PASSWORD = '[^']*'" "$REPO/api/database/seeders/StaffSeeder.php" | cut -d"'" -f2)"
STAFF_PASS="${STAFF_PASS:-password}"

MIN_SDK="$(grep -oE 'minSdk = [0-9]+' "$REPO/app/android/app/build.gradle" | grep -oE '[0-9]+')"

cat > "$REPO/information.txt" <<EOF
