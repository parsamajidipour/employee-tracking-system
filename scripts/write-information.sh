 THE APK
----------------------------------------------------------------
File            dist/smart-inspection.apk   (~50 MB)
Package         com.smartinspection.tracking
Minimum         Android $(case "$MIN_SDK" in 21) echo "5.0";; 23) echo "6.0";; 24) echo "7.0";; 26) echo "8.0";; *) echo "API $MIN_SDK";; esac) (API ${MIN_SDK})
