One APK for every phone: all three ABIs are in it, so it installs
on 32-bit and 64-bit ARM devices and on x86_64 emulators alike.

API ${MIN_SDK} is the real floor, not a preference. shared_preferences
(pulled in transitively) requires 24 and flutter_secure_storage
requires 23. Nothing in the app itself needs above 21.

To install: copy the APK to the phone and open it. Android will ask
you to allow installing from unknown sources, because this is not
distributed through Play.

Cleartext HTTP is allowed only for localhost, 10.0.2.2 and
${LAN_HOST}, and refused everywhere else, so the app cannot be
tricked into sending data unencrypted to an arbitrary host. Put a
TLS terminator in front of the API before this leaves a trusted
network.

Signing keys live in app/android/key.properties and
app/android/smartinspection-release.jks. Both are git-ignored.
Back them up: losing them means no future build can upgrade an
already-installed app.

